# Reader (readTopology, stuff.C:49-245)

class GauSyntaxError(ValueError):
    pass


class _Stream:
    """The few istream operations readTopology uses: '>> char' and '>> int' both skip blanks."""

    def __init__(self, text):
        self.s, self.i = text, 0

    def char(self):
        while self.i < len(self.s) and self.s[self.i].isspace():
            self.i += 1
        if self.i >= len(self.s):
            raise GauSyntaxError('unexpected end of string')
        self.i += 1
        return self.s[self.i - 1]

    def back(self):
        self.i -= 1

    def int(self):
        while self.i < len(self.s) and self.s[self.i].isspace():
            self.i += 1
        m = re.compile(r'[+-]?\d+').match(self.s, self.i)
        if not m:
            raise GauSyntaxError('integer expected at offset %d of %r' % (self.i, self.s))
        self.i = m.end()
        return int(m.group())


def _runs(st, close, colours):
    out = []
    c = st.char()
    while c != close:
        if c == '.':
            out += [0] * st.int()
        else:
            if colours and c == 'a':
                v = ANY
            else:
                st.back()
                v = st.int()
            if v == 0:
                # GAU skips the '^' parse and reuses the previous (or an uninitialised) run length
                raise GauSyntaxError("literal 0 in %r: GAU writes zeros as '.k' only" % st.s)
            c = st.char()
            if c == '^':
                n = st.int()
            else:
                st.back()
                n = 1
            out += [v] * n
        c = st.char()
    return out


def parse(text):
    """Parse a GAU topology string; raise GauSyntaxError where GAU would return the empty graph
    (or misbehave).  Characters between the vertex count and '(' are skipped, as in GAU."""
    st = _Stream(text.strip())
    V = st.int()
    if V <= 0:
        raise GauSyntaxError('vertex count must be positive (GAU: 0 = end of list)')
    while st.char() != '(':
        pass
    colours = [0] * V
    diag = [0] * V
    c = st.char()
    if c == '<':
        colours = _runs(st, '>', True)
        if len(colours) != V:
            raise GauSyntaxError('%d colours for %d vertices in %r' % (len(colours), V, text))
    else:
        st.back()
    c = st.char()
    if c == '[':
        diag = _runs(st, ']', False)
        if len(diag) != V:
            raise GauSyntaxError('%d self-loop codes for %d vertices in %r' % (len(diag), V, text))
    else:
        st.back()
    tri = _runs(st, ')', False)
    if len(tri) != V * (V - 1) // 2:
        raise GauSyntaxError('%d upper-triangle codes, %d expected, in %r' % (len(tri), V * (V - 1) // 2, text))
    adj = [[0] * V for _ in range(V)]
    for i in range(V):
        adj[i][i] = diag[i]
    k = 0
    for i in range(V):
        for j in range(i + 1, V):
            adj[i][j] = adj[j][i] = tri[k]
            k += 1
    for row in adj:
        for code in row:
            lineset(code)
    return Graph(colours, adj)


def repair_preII(text):
    """The 13 strings of PARIS/chrome/Pre-II/paris.{script,results} lost the first upper-triangle
    value '1' (e.g. '4(^6)' for '4(1^6)').  Re-insert it if, and only if, the string does not
    parse as it is but parses with it.  Returns (graph, repaired_string_or_None)."""
    try:
        return parse(text), None
    except GauSyntaxError as first:
        m = re.match(r'^(\s*\d+[^(]*\((?:<[^>]*>)?(?:\[[^\]]*\])?)([\^ .].*)$', text)
        if not m:
            raise
        fixed = m.group(1) + '1' + m.group(2)
        try:
            return parse(fixed), fixed
        except GauSyntaxError:
            raise first


