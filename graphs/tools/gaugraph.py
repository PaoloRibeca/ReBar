def _explain(s):
    g, fixed = repair_preII(s)
    out = ['%s' % s]
    if fixed:
        out.append('  NOTE: does not parse as written; repaired (Pre-II defect) to %s' % fixed)
    am = g.amputated()
    out.append('  V = %d, colours = %s' % (g.V, ['a' if c == ANY else c for c in g.colours]))
    out.append('  amputated colours = %s' % ['a' if c == ANY else c for c in am.colours])
    for i in range(g.V):
        for j in range(i, g.V):
            code = g.adj[i][j]
            if code:
                ms = lineset(code)
                desc = ', '.join('%d x type %d (%s)' % (ms.count(t), t, LINE_TYPE_NAMES[t]) for t in sorted(set(ms)))
                out.append('  %s %d-%d: code %d = {%s}' % ('self-loop' if i == j else 'lines    ', i, j, code, desc))
    if all(c <= 0 and c != ANY for c in g.colours):
        out.append('  legs = %s (E = %d), lines = %d, loops = %d, self-loops = %d'
                   % (g.legs(), sum(g.legs()), len(g.lines()), g.loops(), g.selfloops()))
        out.append('  1PI = %d, 1VR = %d, generalized tadpole = %d'
                   % (g.is_1pi(), g.is_1vr(), g.is_generalized_tadpole()))
        out.append('  canonical (raw colours)   = %s' % g.canonical().gau())
        out.append('  canonical (amputated)     = %s' % am.canonical().gau())
        typed = not g.is_plain()
        out.append('  Nickel%s = %s' % (' (line types ignored)' if typed else '', g.nickel(ignore_types=True)))
        if not typed and sum(g.legs()) in (2, 4):
            out.append('  weight (globalSymmetryFactor) = %s' % g.weight())
    else:
        out.append('  loops = %d (effective or wildcard vertices: no legs, Nickel or weight)' % g.loops())
    return '\n'.join(out)


def _inputs(args):
    if args:
        return args
    return [l.strip() for l in sys.stdin if l.strip()]


def _graph(s):
    """parse() with the Pre-II repair, reporting the repair on stderr."""
    g, fixed = repair_preII(s)
    if fixed:
        sys.stderr.write('gaugraph: %r repaired to %r (Pre-II defect)\n' % (s, fixed))
    return g


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd')
    sub.required = True   # Python 3.6 has no required= keyword here
    p = sub.add_parser('decode', help='explain GAU strings')
    p.add_argument('strings', nargs='*')
    p = sub.add_parser('nickel', help='GAU string -> Nickel index')
    p.add_argument('--gau-style', action='store_true', help="GAU nickelizer.C output ('/EE12/.../')")
    p.add_argument('--ignore-types', action='store_true', help='drop line types (derivative terms)')
    p.add_argument('strings', nargs='*')
    p = sub.add_parser('gau', help='Nickel index -> GAU string')
    p.add_argument('nickel', nargs='*')
    p = sub.add_parser('canon', help='GAU canonical form')
    p.add_argument('-a', '--amputate', action='store_true', help='colour-amputate first (beta.specs form)')
    p.add_argument('strings', nargs='*')
    p = sub.add_parser('amputate', help='colour-amputated form, own vertex order')
    p.add_argument('strings', nargs='*')
    p = sub.add_parser('adj', help='V, self-loops per vertex and upper-triangle line counts, plain integers')
    p.add_argument('strings', nargs='*')
    p = sub.add_parser('lookup', help='find strings or Nickel indices in gau_lists.tsv')
    p.add_argument('-t', '--tsv', default=DEFAULT_TSV)
    p.add_argument('keys', nargs='*')
    p = sub.add_parser('lists', help='rebuild gau_lists.tsv from the GAU list files')
    p.add_argument('-d', '--dir', default=DEFAULT_GAU, help='directory of GAU-format lists (default: %(default)s)')
    p.add_argument('-o', '--output', default='-')
    sub.add_parser('selftest', help='internal checks')
    a = ap.parse_args(argv)

    def each(items, fn):
        status = 0
        for s in _inputs(items):
            try:
                fn(s)
            except ValueError as e:
                sys.stderr.write('gaugraph: %s: %s\n' % (s, e))
                status = 1
        return status

    if a.cmd == 'selftest':
        selftest()
        return 0
    if a.cmd == 'lists':
        if a.output == '-':
            build_tsv(a.dir, sys.stdout)
        else:
            with open(a.output, 'w') as fh:
                build_tsv(a.dir, fh)
        return 0
    if a.cmd == 'decode':
        return each(a.strings, lambda s: print(_explain(s)))
    if a.cmd == 'nickel':
        return each(a.strings, lambda s: print(s, _graph(s).gau_nickelizer() if a.gau_style
                                               else _graph(s).nickel(ignore_types=a.ignore_types), sep='\t'))
    if a.cmd == 'gau':
        return each(a.nickel, lambda s: print(s, from_nickel(s).gau(), sep='\t'))
    if a.cmd == 'canon':
        return each(a.strings, lambda s: print(s, (_graph(s).amputated() if a.amputate else _graph(s))
                                               .canonical().gau(), sep='\t'))
    if a.cmd == 'amputate':
        return each(a.strings, lambda s: print(s, _graph(s).amputated().gau(), sep='\t'))
    if a.cmd == 'adj':
        def adj(s):
            g = _graph(s)
            print(' '.join(str(x) for x in [g.V] + [g.nlines(i, i) for i in range(g.V)]
                           + [g.nlines(i, j) for i in range(g.V) for j in range(i + 1, g.V)]))
        return each(a.strings, adj)
    if a.cmd == 'lookup':
        by_nk = {}
        for r in read_tsv(a.tsv):
            by_nk.setdefault(r['nickel'], []).append(r)

        def look(k):
            nk = k if '|' in k else _graph(k).nickel()
            hits = by_nk.get(nk, [])
            if not hits:
                print('%s\t%s\tnot in the GAU lists' % (k, nk))
            for r in hits:
                print('\t'.join([k, nk] + [r[c] for c in TSV_HEADER]))
        return each(a.keys, look)

if __name__ == '__main__':
    sys.exit(main())
