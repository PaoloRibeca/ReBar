# GAU list files and labels

def list_labels(strings, npoint):
    """labelFactory numbering of a list file (stuff.C:4031-4046, 4669-4688, 4737-4746): D40L<L>N<k>
    in file order for 4-point lists; D20L<L>N<k> for 2-point graphs with at most one self-loop
    line (graphs with more are skipped and get None)."""
    prefix = 'D20' if npoint == 2 else 'D40'
    count, out = {}, []
    for s in strings:
        g = parse(s)
        if npoint == 2 and g.selfloops() >= 2:
            out.append(None)
            continue
        L = g.loops()
        count[L] = count.get(L, 0) + 1
        out.append('%sL%dN%d' % (prefix, L, count[L]))
    return out


def _integrand_index(gau_dir):
    """Integrand functions of the 5-loop (integrands.C~) and 7-loop (integrands.VII.C) files, indexed
    by list label: {label: [number of direct parametrisations, set of D2D components]}."""
    idx = {}
    for f, pat in (('integrands.C~', r'^#define INTEGRAND (\w+)$'),
                   ('integrands.VII.C', r'^extern "C" void (\w+)\(')):
        p = os.path.join(gau_dir, f)
        if not os.path.exists(p):
            continue
        rx = re.compile(pat)
        with open(p, errors='replace') as fh:
            for line in fh:
                m = rx.match(line)
                if not m:
                    continue
                name = m.group(1)
                d = re.match(r'(D[24]0L\d+N\d+)P\d+$', name)
                c = re.match(r'D2D(L\d+N\d+)(C\d+)P\d+$', name)
                if d:
                    idx.setdefault(d.group(1), [0, set()])[0] += 1
                elif c:
                    idx.setdefault('D20' + c.group(1), [0, set()])[1].add(c.group(2))
    return idx


TSV_HEADER = ['list', 'line', 'label', 'gau', 'nickel', 'V', 'E', 'L', 'selfloops', '1VR', 'gentad',
              'weight', 'integrands']


def build_tsv(gau_dir, out):
    """Write the gau_lists.tsv table for every N-loop-K list in gau_dir."""
    index = _integrand_index(gau_dir)
    out.write('#' + '\t'.join(TSV_HEADER) + '\n')
    files = sorted((f for f in os.listdir(gau_dir) if re.fullmatch(r'\d+-loop-[24]', f)),
                   key=lambda f: (int(f.split('-')[2]), int(f.split('-')[0])))
    for f in files:
        npoint = int(f.split('-')[2])
        with open(os.path.join(gau_dir, f)) as fh:
            strings = [l.strip() for l in fh if l.strip()]
        for idx, (s, lab) in enumerate(zip(strings, list_labels(strings, npoint)), 1):
            g = parse(s)
            fns = '-'
            if lab and g.loops() in (5, 7):
                n_direct, comps = index.get(lab, [0, set()])
                parts = []
                if n_direct:
                    parts.append('%s:%d' % (lab[:3], n_direct))
                if comps:
                    parts.append('D2D:%d' % len(comps))
                fns = ','.join(parts) if parts else '0'
            row = [f, idx, lab or '-', s, g.nickel(), g.V, sum(g.legs()), g.loops(), g.selfloops(),
                   int(g.is_1vr()), int(g.is_generalized_tadpole()), g.weight(), fns]
            out.write('\t'.join(str(x) for x in row) + '\n')


def read_tsv(path=DEFAULT_TSV):
    rows = []
    with open(path) as fh:
        for line in fh:
            if line.startswith('#') or not line.strip():
                continue
            rows.append(dict(zip(TSV_HEADER, line.rstrip('\n').split('\t'))))
    return rows


