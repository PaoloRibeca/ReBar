# Self-test

def selftest(verbose=True):
    # code table
    assert len(CODE2SET) == 284
    assert lineset(1) == (1,) and lineset(4) == (1, 1, 1, 1)
    assert lineset(5) == (2,) and lineset(6) == (1, 2) and lineset(7) == (1, 1, 2)
    assert lineset(15) == (3,) and lineset(16) == (1, 3) and lineset(45) == (4,)
    assert lineset(283) == (4, 4, 4, 4, 5, 5, 6, 7, 8, 9)
    for c in range(45):
        n1, n2, n3 = c % 5, (c // 5) % 3, c // 15
        assert lineset(c) == (1,) * n1 + (2,) * n2 + (3,) * n3
    # round trips of strings quoted by GAU, PARIS and the thesis
    for s in ['1([1])', '1(<-4>)', '2([.1 1]2)', '2(<-1^2>3)', '3(1^2 3)', '3([.1 1.1].1 2^2)', '4(1^6)',
              '5(<-2.2 -1^2>1^2.2 1^6)', '6(.2 1^2.2 1^6.1 1^2)', '4(<-1^2.2>.1 1 6 2 15 1)',
              '5(.1 1.1 2.1 15 2 7.2)', '4(<a^4>1.1 1^2.1 1)', '7(1.1 1.1 1.1 1^3.3 1.1 1^3.2 1^2)']:
        assert parse(s).gau() == s, s
    # lexical freedom: blanks anywhere between tokens, '-' ends a number, junk before '('
    assert parse('5 junk ( < -2 . 2 -1 ^ 2 > 1^2 .2 1 ^6 )').gau() == '5(<-2.2 -1^2>1^2.2 1^6)'
    assert parse('4(<-1-1.2>.1 1 6 2 15 1)').gau() == '4(<-1^2.2>.1 1 6 2 15 1)'
    for bad in ['3(1^2)', '3(0 1^2 3)', '3(1^2 3', '2(a)', '3(.1^2 1 3)']:
        try:
            parse(bad)
        except GauSyntaxError:
            pass
        else:
            raise AssertionError('accepted malformed %r' % bad)
    assert repair_preII('4(^6)')[1] == '4(1^6)'
    assert repair_preII('5(.2 2 1^2.1 1^3)')[1] == '5(1.2 2 1^2.1 1^3)'
    # decoded examples
    g = parse('6(.2 1^2.2 1^6.1 1^2)')
    assert g.legs() == [2, 1, 1, 0, 0, 0] and g.loops() == 5
    assert g.amputated().canonical().gau() == '6(<-2 -1^2.3>.3 1^2.1 1^8.1)'
    assert g.nickel() == 'ee12|345|345|e4|5|e|'
    assert g.gau_nickelizer() == '/EE12/345/345/E4/5/E/'
    g = parse('5(<-2.2 -1^2>1^2.2 1^6)')
    assert g.canonical().gau() == '5(<-2 -1^2.2>.2 1^8)' and g.nickel() == 'ee12|234|34|e4|e|'
    assert g.same_as(parse('5(1^2.2 1^6)').amputated())
    assert parse('3([.1 1.1].1 2^2)').nickel() == 'ee11|22|2|'
    assert parse('4(2 1.2 1 3)').amputated().canonical().gau() == '4(<-1^2.2>2.1 1^2.1 3)'
    assert parse('4(2.2 1^2 3)').canonical().gau() == parse('4(.1 3 1.1 2 1)').canonical().gau() == '4(.2 2 3 1^2)'
    assert parse('4(2 1.2 1 3)').nickel() == 'e112|e3|333||'
    assert from_nickel('ee12|e22|e|').gau() == '3(1^2 2)'
    # weights (beta.specs lines D20L2N2, D20L3N1, D40L4N20)
    assert parse('2(3)').weight() == Fraction(1, 6)
    assert parse('3(1^2 3)').weight() == Fraction(1, 12)
    assert parse('5(1^2.2 1^6)').weight() == 3
    # O(N) factors (beta.specs D40L1N1, D20L2N2, D20L4N9)
    assert parse('2(2)').on_string() == '1/9*(n+8)' and parse('2(3)').on_string() == '1/3*(n+2)'
    assert parse_on('1/81*(5*n^2+32*n+44)') == parse('4(.1 1 2^2 1^2)').on_factor()
    assert format_on(parse_on('1/27*(n^3+6*n^2+12*n+8)')) == '1/27*(n^3+6*n^2+12*n+8)'
    # branch and bound = brute force on small graphs
    import random
    rnd = random.Random(7)
    for s in ['4(1^6)', '6(.2 1^2.2 1^6.1 1^2)', '5(1^2.2 1^6)', '4([.1 1.2]1^2.2 1 3)']:
        g = parse(s)
        assert g.nickel() == g.nickel_bruteforce(), s
        for _ in range(5):
            p = list(range(g.V))
            rnd.shuffle(p)
            h = g.permuted(p)
            assert h.nickel() == g.nickel() and h.canonical().gau() == g.canonical().gau(), s
            assert h.amputated().canonical().gau() == g.amputated().canonical().gau(), s
    if verbose:
        print('selftest: all checks passed')


