# Line-set codes (stuff.C:3196-3201, library/graph.C:576-599, integerMap.C:953-967)
#
# setupGraphs registers the maximal multisets {1,1,1,1,2,2,3,3} (phi^4 lines) and
# {4,4,4,4,5,5,6,7,8,9} (momentum-conservation lines of effective vertices).  Their
# sub-multisets get consecutive codes in odometer order, lowest line type fastest; the
# empty set is code 0.  Hence code = n1 + 5 n2 + 15 n3 for 0..44 and
# 44 + n4 + 5 n5 + 15 n6 + 30 n7 + 60 n8 + 120 n9 for 45..283.

def _odometer(maximal):
    types = sorted(set(maximal))
    lim = [maximal.count(t) for t in types]
    digits = [0] * len(types)
    yield ()
    while True:
        p = 0
        while True:
            digits[p] += 1
            if digits[p] <= lim[p]:
                break
            digits[p] = 0
            p += 1
            if p == len(types):
                return
        yield tuple(t for t, d in zip(types, digits) for _ in range(d))


def _build_codes():
    c2s, s2c = {0: ()}, {(): 0}
    for maximal in ((1, 1, 1, 1, 2, 2, 3, 3), (4, 4, 4, 4, 5, 5, 6, 7, 8, 9)):
        for ms in _odometer(list(maximal)):
            if ms not in s2c:
                s2c[ms] = len(c2s)
                c2s[len(c2s)] = ms
    return c2s, s2c


CODE2SET, SET2CODE = _build_codes()
