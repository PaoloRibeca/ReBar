def lineset(code):
    """Multiset of line types (a sorted tuple) for a line-set code."""
    try:
        return CODE2SET[code]
    except KeyError:
        raise ValueError('line-set code %d is not defined (GAU: undefined behaviour)' % code)


def code_of(types):
    """Line-set code of a multiset of line types."""
    key = tuple(sorted(types))
    try:
        return SET2CODE[key]
    except KeyError:
        raise ValueError('multiset %r has no static code (GAU would assign one at run time)' % (key,))


