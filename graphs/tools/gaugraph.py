# Writer (writeTopology, stuff.C:246-362)

def _rle(vals, colours=False):
    out = []
    for idx, (v, grp) in enumerate(itertools.groupby(vals)):
        n = len(list(grp))
        if v:
            tok = 'a' if (colours and v == ANY) else str(v)
            out.append(('' if idx == 0 else ' ') + tok + ('^%d' % n if n > 1 else ''))
        else:
            out.append('.%d' % n)
    return ''.join(out)


class Graph:
    """A GAU graph: vertex colours and a symmetric matrix of line-set codes (diagonal = self-loops)."""

    def __init__(self, colours, adj):
        self.V = len(colours)
        self.colours = list(colours)
        self.adj = [list(r) for r in adj]

    # -- output -------------------------------------------------------------------------------
    def gau(self):
        """writeTopology(..., canonical=false): the string in this graph's own vertex order."""
        V = self.V
        s = '%d(' % V
        if any(self.colours):
            s += '<' + _rle(self.colours, True) + '>'
        diag = [self.adj[i][i] for i in range(V)]
        if any(diag):
            s += '[' + _rle(diag) + ']'
        s += _rle([self.adj[i][j] for i in range(V) for j in range(i + 1, V)])
        return s + ')'

    __str__ = gau

    def permuted(self, perm):
        """New graph whose vertex k is old vertex perm[k]."""
        V = self.V
        return Graph([self.colours[perm[k]] for k in range(V)],
                     [[self.adj[perm[a]][perm[b]] for b in range(V)] for a in range(V)])

    # -- elementary quantities -----------------------------------------------------------------
    def nlines(self, i, j):
        return len(lineset(self.adj[i][j]))

    def lines(self):
        """List of (i, j, type) with i <= j; self-loops have i == j."""
        out = []
        for i in range(self.V):
            for j in range(i, self.V):
                out += [(i, j, t) for t in lineset(self.adj[i][j])]
        return out

    def half_edges(self, i):
        return sum((2 if i == j else 1) * self.nlines(i, j) for j in range(self.V))

    def selfloops(self):
        """numberOfTadpolesIn (stuff.C:364-369): number of self-loop lines."""
        return sum(self.nlines(i, i) for i in range(self.V))

    def components(self, removed=()):
        par = list(range(self.V))

        def f(x):
            while par[x] != x:
                par[x] = par[par[x]]
                x = par[x]
            return x
        for i in range(self.V):
            for j in range(i + 1, self.V):
                if self.adj[i][j] and i not in removed and j not in removed:
                    par[f(i)] = f(j)
        return len({f(x) for x in range(self.V) if x not in removed})

    def loops(self):
        """cyclomaticNumber (library/graph.C:1689-1710): lines - V + components."""
        return len(self.lines()) - self.V + self.components()

    def amputated(self):
        """colorAmputatedTopology: every colour-0 vertex gets (half-edges - 4)."""
        c = [col if col else self.half_edges(i) - 4 for i, col in enumerate(self.colours)]
        return Graph(c, self.adj)

    def legs(self):
        """External legs per vertex (None for effective or wildcard vertices)."""
        out = []
        for col in self.amputated().colours:
            out.append(-col if col <= 0 and col != ANY else None)
        return out

    def is_plain(self):
        return all(t == 1 for _i, _j, t in self.lines()) and all(c <= 0 and c != ANY for c in self.colours)

    # -- predicates ----------------------------------------------------------------------------
    def is_1pi(self):
        if self.components() != 1:
            return False
        for i in range(self.V):
            for j in range(i + 1, self.V):
                if self.nlines(i, j) == 1:
                    saved = self.adj[i][j]
                    self.adj[i][j] = self.adj[j][i] = 0
                    bridge = self.components() > 1
                    self.adj[i][j] = self.adj[j][i] = saved
                    if bridge:
                        return False
        return True

    def is_1vr(self):
        """One-vertex-reducible: removing some vertex disconnects the rest (cut vertex).  For 1PI
        phi^4 graphs this is GAU's factorizability test isWithoutCutVertices (stuff.C:372-528)."""
        return self.V >= 3 and any(self.components(removed=(v,)) > 1 for v in range(self.V))

    def is_generalized_tadpole(self):
        """isAGeneralizedTadpole (stuff.C:550-561): two legs in total, both on one vertex."""
        c = self.amputated().colours
        return sum(c) == -2 and -2 in c

    # -- automorphisms and the combinatorial weight ----------------------------------------------
    def automorphisms(self):
        """Number of vertex permutations preserving colours (after amputation) and the code matrix
        (graph::automorphismGroupDim, library/graph.C:1050-1100)."""
        g = self.amputated()
        V, A, C = g.V, g.adj, g.colours
        sig = [(C[i], A[i][i], tuple(sorted(A[i][j] for j in range(V) if j != i))) for i in range(V)]
        img = [None] * V
        used = [False] * V

        def rec(k):
            if k == V:
                return 1
            n = 0
            for w in range(V):
                if not used[w] and sig[w] == sig[k] and all(A[k][j] == A[w][img[j]] for j in range(k)):
                    used[w], img[k] = True, w
                    n += rec(k + 1)
                    used[w], img[k] = False, None
            return n
        return rec(0)

    def weight(self):
        """globalSymmetryFactor (stuff.C:573-601): E! link(A) / ((4!)^V |Aut_V|), as a Fraction.
        Plain phi^4 graphs only (GAU aborts on effective vertices)."""
        if any(self.colours):
            g = Graph([0] * self.V, self.adj)
        else:
            g = self
        res = Fraction(1, 24 ** g.V * g.automorphisms())
        ext = 0
        for i in range(g.V):
            rem = 4
            for j in range(g.V):
                d = g.nlines(i, j)
                if not d:
                    continue
                if i == j:
                    d *= 2
                    res *= _dfact(d - 1)
                elif i < j:
                    res *= math.factorial(d)
                res *= _comb(rem, d)
                rem -= d
            ext += rem
        return res * math.factorial(ext)

    # -- O(N) factor --------------------------------------------------------------------------
    def on_factor(self):
        """O(N) tensor factor as {power of N: Fraction}: every 4-valent vertex carries
        S_abcd = (d_ab d_cd + d_ac d_bd + d_ad d_bc)/3, every closed index loop gives N, and the
        coefficients of the remaining external structures are summed (symmetrizedONPolynomial +
        deltas.C, stuff.C:603-639).  Plain phi^4 graphs only; 3^V terms."""
        if not self.is_plain():
            raise ValueError('O(N) factor defined here for plain phi^4 graphs only')
        V = self.V
        slots = []                    # per vertex: list of half-edge ids
        legs = set()
        nxt = [0]

        def new():
            nxt[0] += 1
            return nxt[0] - 1
        line_pairs = []
        own = [[] for _ in range(V)]
        for i, j, _t in self.lines():
            a, b = new(), new()
            own[i].append(a)
            own[j].append(b)
            line_pairs.append((a, b))
        for v, k in enumerate(self.legs()):
            for _ in range(k):
                h = new()
                own[v].append(h)
                legs.add(h)
        for v in range(V):
            if len(own[v]) != 4:
                raise ValueError('vertex %d is not 4-valent' % v)
            slots.append(own[v])
        n = nxt[0]
        res = {}
        for choice in itertools.product(range(3), repeat=V):
            par = list(range(n))

            def f(x):
                while par[x] != x:
                    par[x] = par[par[x]]
                    x = par[x]
                return x
            for a, b in line_pairs:
                par[f(a)] = f(b)
            for v, c in enumerate(choice):
                h = slots[v]
                for a, b in (((h[0], h[1]), (h[2], h[3])), ((h[0], h[2]), (h[1], h[3])),
                             ((h[0], h[3]), (h[1], h[2])))[c]:
                    par[f(a)] = f(b)
            roots_with_legs = {f(x) for x in legs}
            closed = len({f(x) for x in range(n)} - roots_with_legs)
            res[closed] = res.get(closed, 0) + 1
        return {k: Fraction(v, 3 ** V) for k, v in sorted(res.items())}

    def on_string(self):
        """The O(N) factor printed as GAU prints it in beta.specs, e.g. '1/9*(n+8)'."""
        return format_on(self.on_factor())

    # -- GAU canonical form ------------------------------------------------------------------
    def canonical(self):
        """graph::canonize (library/graph.C:860-1048).  (i) vertex invariant = sorted multiset of
        the non-zero codes of its row (diagonal included) and column (diagonal excluded), ordered by
        size then lexicographically; (ii) classes = (colour rank, invariant rank), ascending;
        (iii) the class-respecting vertex order with the lexicographically smallest full V x V
        code matrix (row-major).  Exact; cost = product of factorials of the class sizes."""
        V, A, C = self.V, self.adj, self.colours
        inv = []
        for i in range(V):
            b = [A[i][j] for j in range(V)] + [A[j][i] for j in range(V) if j != i]
            inv.append(tuple(sorted(x for x in b if x)))
        irank = {k: r for r, k in enumerate(sorted(set(inv), key=lambda t: (len(t), t)))}
        crank = {k: r for r, k in enumerate(sorted(set(C)))}
        key = [(crank[C[i]], irank[inv[i]]) for i in range(V)]
        classes = [[i for i in range(V) if key[i] == k] for k in sorted(set(key))]
        best = bestp = None
        for combo in itertools.product(*[itertools.permutations(c) for c in classes]):
            p = [v for part in combo for v in part]
            m = tuple(A[p[a]][p[b]] for a in range(V) for b in range(V))
            if best is None or m < best:
                best, bestp = m, p
        return self.permuted(bestp)

    def same_as(self, other):
        """graph::operator== : equal vertex count, canonical colours and canonical matrix."""
        a, b = self.canonical(), other.canonical()
        return a.colours == b.colours and a.adj == b.adj

    # -- Nickel indices ----------------------------------------------------------------------
    def _plain_check(self, ignore_types):
        if any(c > 0 for c in self.colours) or ANY in self.colours:
            raise ValueError('Nickel index undefined for effective or wildcard vertices')
        if not ignore_types and any(t != 1 for _i, _j, t in self.lines()):
            raise ValueError('typed (numerator) lines present; pass ignore_types=True to drop types')

    def nickel(self, ignore_types=False):
        """Canonical Nickel index in the Phi4tools / rebar convention: per vertex 'e' per
        leg, then the sorted labels >= its own of the vertices it is joined to (own label for a
        self-loop), then '|'; minimum over relabellings with '|' < 'e' < '0' < ... < '9' < 'A' ...
        Exact branch and bound (equal to brute force, see selftest)."""
        self._plain_check(ignore_types)
        V = self.V
        ext = self.legs()
        m = [[self.nlines(i, j) for j in range(V)] for i in range(V)]
        best = [None]

        def prefix_key(order):
            pos = {v: k for k, v in enumerate(order)}
            key = []
            for k, v in enumerate(order):
                key += [1] * ext[v]
                labs, unplaced = [], False
                for w in range(V):
                    if m[v][w]:
                        if w in pos:
                            if pos[w] >= k:
                                labs += [pos[w]] * m[v][w]
                        else:
                            unplaced = True
                key += [2 + x for x in sorted(labs)]
                if unplaced:
                    return key, False
                key.append(0)
            return key, len(order) == V

        def rec(order):
            key, complete = prefix_key(order)
            if best[0] is not None and key > best[0][:len(key)]:
                return
            if complete:
                if best[0] is None or key < best[0]:
                    best[0] = key
                return
            placed = set(order)
            cand = None
            for v in order:
                nb = [w for w in range(V) if m[v][w] and w not in placed]
                if nb:
                    cand = nb
                    break
            if cand is None:
                cand = [w for w in range(V) if w not in placed]
            for w in cand:
                rec(order + [w])
        rec([])
        return ''.join('|' if r == 0 else 'e' if r == 1 else _vchar(r - 2) for r in best[0])

    def nickel_bruteforce(self, ignore_types=False):
        self._plain_check(ignore_types)
        return min((_nickel_string(self, p) for p in itertools.permutations(range(self.V))), key=_nk_key)

    def gau_nickelizer(self):
        """Mirror of GAU/nickelizer.C:10-49 (V <= 9): minimise, over vertex orders, the separator-free
        key (' ' per leg, the vertex's own index once if it has a self-loop, then index j > i once per
        line) and print the '/'-separated form with 'E' for legs."""
        if self.V > 9:
            raise ValueError('nickelizer.C refuses graphs with more than 9 vertices')
        ext = self.legs()
        V = self.V
        m = [[self.nlines(i, j) for j in range(V)] for i in range(V)]
        best = None
        for perm in itertools.permutations(range(V)):
            key, out = [], []
            for i in range(V):
                key.append(' ' * ext[perm[i]])
                blk = 'E' * ext[perm[i]] + (str(i) if m[perm[i]][perm[i]] else '')
                key.append(str(i) if m[perm[i]][perm[i]] else '')
                for j in range(i + 1, V):
                    blk += str(j) * m[perm[i]][perm[j]]
                    key.append(str(j) * m[perm[i]][perm[j]])
                out.append(blk)
            k = ''.join(key)
            if best is None or k < best[0]:
                best = (k, '/' + '/'.join(out) + '/')
        return best[1]


def format_on(poly):
    """{power: Fraction} -> GAU's 'r*(integer polynomial in n)' notation."""
    poly = {k: v for k, v in poly.items() if v}
    if not poly:
        return '0'
    den = 1
    for v in poly.values():
        den = den * v.denominator // math.gcd(den, v.denominator)
    ints = {k: int(v * den) for k, v in poly.items()}
    g = 0
    for v in ints.values():
        g = math.gcd(g, v)
    ints = {k: v // g for k, v in ints.items()}
    r = Fraction(g, den)
    terms = []
    for k in sorted(ints, reverse=True):
        c = ints[k]
        mono = '' if k == 0 else 'n' if k == 1 else 'n^%d' % k
        body = str(abs(c)) if not mono else (mono if abs(c) == 1 else '%d*%s' % (abs(c), mono))
        terms.append(('-' if c < 0 else '+') + body)
    p = ''.join(terms).lstrip('+')
    if len(ints) == 1 and 0 in ints:
        return str(r * ints[0])
    return '%s*(%s)' % (r if r.denominator != 1 else r.numerator, p) if r != 1 else p


def parse_on(text):
    """GAU's O(N) notation ('1/27*(n^3+6*n^2+12*n+8)', '1', '1/3*(n+2)') -> {power: Fraction}."""
    text = text.strip()
    m = re.fullmatch(r'([0-9/]+)\*\((.*)\)', text)
    r, body = (Fraction(m.group(1)), m.group(2)) if m else (Fraction(1), text)
    out = {}
    for sign, coef, mono in re.findall(r'([+-]?)\s*(\d+(?:/\d+)?)?\*?(n(?:\^\d+)?)?', body):
        if not coef and not mono:
            continue
        c = Fraction(coef) if coef else Fraction(1)
        k = 0 if not mono else 1 if mono == 'n' else int(mono[2:])
        out[k] = out.get(k, 0) + (-c if sign == '-' else c) * r
    return {k: v for k, v in sorted(out.items()) if v}


def _comb(n, k):
    return math.factorial(n) // (math.factorial(k) * math.factorial(n - k)) if 0 <= k <= n else 0


def _dfact(n):
    r = 1
    while n > 1:
        r *= n
        n -= 2
    return r


def _vchar(v):
    return chr(48 + v) if v < 10 else chr(55 + v)


def _nk_rank(c):
    return 0 if c == '|' else 1 if c == 'e' else 2 + (ord(c) - 48 if c <= '9' else ord(c) - 55)


def _nk_key(s):
    return [_nk_rank(c) for c in s]


def _nickel_string(g, perm):
    """Nickel string of g when vertex perm[k] gets label k."""
    V = g.V
    lab = {perm[k]: k for k in range(V)}
    ext = g.legs()
    nb = [[] for _ in range(V)]
    for i, j, _t in g.lines():
        a, b = sorted((lab[i], lab[j]))
        nb[a].append(b)
    return ''.join('e' * ext[perm[k]] + ''.join(_vchar(w) for w in sorted(nb[k])) + '|' for k in range(V))


def nickel_to_standard(s):
    """GAU nickelizer output '/EE12/.../' -> standard 'ee12|...|'."""
    return s.strip().strip('"')[1:].replace('/', '|').replace('E', 'e')


def from_nickel(nk):
    """Nickel index -> uncoloured GAU graph in the Nickel labelling (external legs implicit)."""
    parts = nk.strip().split('|')
    if parts and parts[-1] == '':
        parts.pop()
    V = len(parts)
    cnt = [[0] * V for _ in range(V)]
    for i, p in enumerate(parts):
        for ch in p:
            if ch == 'e':
                continue
            j = _nk_rank(ch) - 2
            if not i <= j < V:
                raise ValueError('bad Nickel index %r' % nk)
            cnt[i][j] += 1
            if i != j:
                cnt[j][i] += 1
    adj = [[code_of([1] * cnt[i][j]) for j in range(V)] for i in range(V)]
    return Graph([0] * V, adj)


